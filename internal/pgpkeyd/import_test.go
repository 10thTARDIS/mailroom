package pgpkeyd

// `import` inverts the direction of the risk this package is built around.
//
// Every other method is guarded against private key material coming OUT. Here
// it goes IN, from the caller, and the ways to lose it are different: it can be
// written to a log, quoted back in an error message, or echoed in the response.
// The leak test covers the third (import is in its probe table, with a real key
// as the payload). This file covers the first two, which nothing else would.

import (
	"bytes"
	"context"
	"log/slog"
	"strings"
	"testing"

	"github.com/oklog/ulid/v2"

	"mailroom/internal/pgpwire"
)

// startDaemonLogging is startDaemon with the daemon's logger captured, so a
// test can read everything the process wrote while handling a request.
func startDaemonLogging(t *testing.T) (*harness, *bytes.Buffer) {
	t.Helper()
	var logged bytes.Buffer
	h := startDaemonWithLogger(t, slog.New(slog.NewTextHandler(&logged, &slog.HandlerOptions{
		Level: slog.LevelDebug, // capture MORE than production would, not less
	})))
	return h, &logged
}

// TestImportDoesNotLogThePrivateKey is the test for the least interesting and
// most likely way to lose an identity key: writing it to a log file.
//
// A private key in a log has defeated the process boundary completely, without
// anyone attacking anything — logs get shipped, tailed, pasted into issues and
// backed up to places the key was never supposed to reach.
func TestImportDoesNotLogThePrivateKey(t *testing.T) {
	h, logged := startDaemonLogging(t)
	ctx := context.Background()
	user := newUserID()

	// A real key, generated by the daemon, exported out of band, then offered
	// back to a DIFFERENT user as an import. Using genuine key material matters:
	// a fabricated string would let the detector pass against something that is
	// not shaped like a key at all.
	seed, err := h.client.Generate(ctx, pgpwire.GenerateRequest{UserID: user, Email: "seed@example.com"})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	priv := h.unsealPrivate(t, seed.Key.KeyID)
	armored := armorPrivateForTest(t, priv)

	importer := newUserID()
	resp, err := h.client.Import(ctx, pgpwire.ImportRequest{UserID: importer, PrivateKey: armored})
	if err != nil {
		t.Fatalf("Import: %v", err)
	}
	if resp.Key.KeyID == "" {
		t.Fatal("import returned no key id")
	}

	// The detector is the same one the leak test uses, and it proves itself
	// there before either test trusts it.
	det := newLeakDetector(t, priv, seed.Key.PublicKey)

	if logged.Len() == 0 {
		t.Fatal("the daemon logged nothing at all during an import — this test would pass vacuously")
	}
	if leak := det.findLeak(logged.Bytes()); leak != "" {
		t.Errorf("the private key reached the log: %s", leak)
	}
	if strings.Contains(logged.String(), "PRIVATE KEY BLOCK") {
		t.Error("the log contains a private key armor header")
	}
}

// TestImportErrorsDoNotQuoteTheInput covers the other inward leak: an error
// message that helpfully includes what it could not parse.
//
// The OpenPGP library's own errors can quote the bytes they choked on, which is
// why Import deliberately does not wrap them.
func TestImportErrorsDoNotQuoteTheInput(t *testing.T) {
	h, logged := startDaemonLogging(t)
	ctx := context.Background()
	user := newUserID()

	seed, err := h.client.Generate(ctx, pgpwire.GenerateRequest{UserID: user, Email: "seed@example.com"})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	priv := h.unsealPrivate(t, seed.Key.KeyID)
	det := newLeakDetector(t, priv, seed.Key.PublicKey)

	// Truncated armor: real key bytes, but not parseable — the shape most
	// likely to make a library error quote its input.
	armored := armorPrivateForTest(t, priv)
	broken := armored[:len(armored)*3/4]

	_, err = h.client.Import(ctx, pgpwire.ImportRequest{UserID: newUserID(), PrivateKey: broken})
	if err == nil {
		t.Fatal("a truncated key was accepted")
	}
	if code, _ := pgpwire.CodeOf(err); code != pgpwire.CodeInvalidRequest {
		t.Errorf("code = %q, want %q", code, pgpwire.CodeInvalidRequest)
	}
	if leak := det.findLeak([]byte(err.Error())); leak != "" {
		t.Errorf("the error message carried private key material: %s", leak)
	}
	if leak := det.findLeak(logged.Bytes()); leak != "" {
		t.Errorf("the failed import logged private key material: %s", leak)
	}
}

// TestImportRoundTrips proves the imported key is the SAME key, by fingerprint,
// and that its stored form opens under this process's root.
func TestImportRoundTrips(t *testing.T) {
	h := startDaemon(t)
	ctx := context.Background()

	origin := newUserID()
	seed, err := h.client.Generate(ctx, pgpwire.GenerateRequest{UserID: origin, Email: "origin@example.com"})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	armored := armorPrivateForTest(t, h.unsealPrivate(t, seed.Key.KeyID))

	importer := newUserID()
	got, err := h.client.Import(ctx, pgpwire.ImportRequest{UserID: importer, PrivateKey: armored})
	if err != nil {
		t.Fatalf("Import: %v", err)
	}
	if got.AlreadyStored {
		t.Error("a first import reported the key as already stored")
	}
	if got.Key.Fingerprint != seed.Key.Fingerprint {
		t.Errorf("fingerprint = %q, want %q — a different key came back", got.Key.Fingerprint, seed.Key.Fingerprint)
	}
	if got.Key.UserID != importer {
		t.Errorf("owner = %q, want the importing user %q", got.Key.UserID, importer)
	}
	// Sealed under the IMPORTER's wrapping key, not the origin user's: the
	// same key held by two users is two rows with two different ciphertexts.
	recovered := h.unsealPrivate(t, got.Key.KeyID)
	if len(recovered) == 0 {
		t.Fatal("the imported key did not unseal")
	}

	// Importing the same key again is a no-op, not a fault.
	again, err := h.client.Import(ctx, pgpwire.ImportRequest{UserID: importer, PrivateKey: armored})
	if err != nil {
		t.Fatalf("second Import: %v", err)
	}
	if !again.AlreadyStored {
		t.Error("importing the same fingerprint twice did not report already_stored")
	}
}

// TestImportRejectsWhatItCannotUse. Each of these would otherwise store
// something that fails later, at send time, far from the cause.
func TestImportRejectsWhatItCannotUse(t *testing.T) {
	h := startDaemon(t)
	ctx := context.Background()
	user := newUserID()

	seed, err := h.client.Generate(ctx, pgpwire.GenerateRequest{UserID: user, Email: "seed@example.com"})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}

	for _, tc := range []struct {
		name string
		req  pgpwire.ImportRequest
	}{
		{"empty", pgpwire.ImportRequest{UserID: newUserID()}},
		{"not a key at all", pgpwire.ImportRequest{UserID: newUserID(), PrivateKey: "hello"}},
		{"a PUBLIC key", pgpwire.ImportRequest{UserID: newUserID(), PrivateKey: seed.Key.PublicKey}},
		{"no user", pgpwire.ImportRequest{PrivateKey: seed.Key.PublicKey}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := h.client.Import(ctx, tc.req); err == nil {
				t.Fatal("accepted")
			} else if code, _ := pgpwire.CodeOf(err); code != pgpwire.CodeInvalidRequest {
				t.Errorf("code = %q, want %q", code, pgpwire.CodeInvalidRequest)
			}
		})
	}
}

// TestBindIdentityRefusesAnotherUsersKey extends the confused-deputy property
// to the method that mutates two tables. Binding is the operation where getting
// the owner wrong would attach one user's key to another user's address — a
// mistake that then signs mail.
func TestBindIdentityRefusesAnotherUsersKey(t *testing.T) {
	h := startDaemon(t)
	ctx := context.Background()

	alice, bob := newUserID(), newUserID()
	aliceKey, err := h.client.Generate(ctx, pgpwire.GenerateRequest{UserID: alice, Email: "alice@example.com"})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}

	_, err = h.client.BindIdentity(ctx, pgpwire.BindIdentityRequest{
		UserID: bob, KeyID: aliceKey.Key.KeyID, IdentityID: ulid.Make().String(),
	})
	if err == nil {
		t.Fatal("bob bound alice's key to an identity")
	}
	if code, _ := pgpwire.CodeOf(err); code != pgpwire.CodeDenied {
		t.Errorf("code = %q, want %q", code, pgpwire.CodeDenied)
	}
}
